    private void llenarFrame() {
        UtilFrame.limpiarTabla(tabla);
        consorcioTxt.setText(comprobante.getCalleNroPisoDtoCliente());
        rubroTxt.setText(comprobante.getRubro().getDetalle());
        nroFcTxt.setText(comprobante.getNumero().toString());
        renglones = null;
        try {
            renglones = new ComprobanteRenglonesService().getRenglonesPorComprobante(comprobante);
        } catch (Exception ex) {
            JOptionPane.showMessageDialog(this, "ERROR EN LOS RENGLONES");
            return;
        }
        DefaultTableModel tbl = (DefaultTableModel) tabla.getModel();
        for (ComprobanteRenglones cr : renglones) {
            Object o[] = new Object[1];
            o[0] = cr.getDetalle();
            tbl.addRow(o);
        }
        tabla.setModel(tbl);
    }

    private void volver() {
        MainFrame mf = new MainFrame();
        mf.setVisible(true);
        this.dispose();
    }

    private void grabar() {
        if (validar()) {
            int r = 0;
            for (ComprobanteRenglones cr : renglones) {
                cr.setDetalle(tabla.getValueAt(r, 0).toString());
                r += 1;
                try {
                    new ComprobanteRenglonesService().updateRenglon(cr);
                } catch (Exception ex) {
                    JOptionPane.showMessageDialog(this, "ERROR GRABANDO RENGLON");
                    return;
                }
            }
            JOptionPane.showMessageDialog(this, "PROCESO TERMINADO");
            volver();
        }
    }

    private boolean validar() {
        if (renglones != null && !renglones.isEmpty()) {
            return true;
        } else {
            return false;
        }
    }
