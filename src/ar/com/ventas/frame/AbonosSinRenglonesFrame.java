    private void go() {
        List<Abono> abonos = null;
        List<Abono> abonosSinRengl = new ArrayList<>();
        try {
            abonos = new AbonoService().getAllAbonosActivos();
        } catch (Exception ex) {
            return;
        }
        if (abonos != null && !abonos.isEmpty()) {
            for (Abono ab : abonos) {
                List<RenglonAbono> renglones = null;
                Double tt1 = 0.0;
                try {
                    renglones = new RenglonAbonoService().getRenglonAbonosByAbono(ab);
                } catch (Exception ex) {

                    JOptionPane.showMessageDialog(this, "ERROR 1815");
                }
                if (renglones == null || renglones.isEmpty()) {
                    abonosSinRengl.add(ab);
                } else {
//                    for(RenglonAbono r1:renglones){
//                        
//                    }
                }
            }
            DefaultTableModel tbl = (DefaultTableModel) tabla.getModel();
            for (Abono abo : abonosSinRengl) {
                Object o[] = new Object[4];
                Domicilio dm = abo.getConsorcio().getDomicilio();
                o[0] = abo.getId();
                o[1] = dm.getCalle() + " "
                        + dm.getNumero();
                o[2] = abo.getRubro().getDetalle();
                o[3] = abo.getCodigo();
                tbl.addRow(o);
            }
            tabla.setModel(tbl);
        }
    }

